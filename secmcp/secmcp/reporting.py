"""CI reporting helpers (GitHub issues + SARIF export)."""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

# SARIF shape inspired by vendor/mcp-guard/mcp_guard/sarif.py (MIT)
SARIF_VERSION = "2.1.0"
SARIF_SCHEMA = "https://json.schemastore.org/sarif-2.1.0.json"
SARIF_LEVELS = {
    "critical": "error",
    "high": "error",
    "medium": "warning",
    "low": "note",
}

_SEVERITY_ORDER = ("critical", "high", "medium", "low")


def format_github_issue(
    scan: dict[str, Any],
    *,
    ref: str = "main",
    sha: str = "",
    docs_url: str = "https://github.com",
) -> tuple[str, str]:
    """Return (title, markdown body) for a daily SecMCP scan issue."""
    counts = scan.get("severity_counts") or {}
    total = int(scan.get("count", 0))
    crit = int(counts.get("critical", 0))
    high = int(counts.get("high", 0))
    med = int(counts.get("medium", 0))
    low = int(counts.get("low", 0))

    title_parts = [f"[SecMCP] Daily scan — {total} finding{'s' if total != 1 else ''}"]
    sev_bits: list[str] = []
    if crit:
        sev_bits.append(f"{crit} critical")
    if high:
        sev_bits.append(f"{high} high")
    if sev_bits:
        title_parts.append(f"({', '.join(sev_bits)})")
    title = " ".join(title_parts)

    overall = scan.get("overall_score", "—")
    grade = scan.get("grade", "—")
    sha_short = sha[:7] if sha else "unknown"

    lines = [
        "## Summary",
        "",
        f"Scheduled SecMCP scan found **{total}** issue(s) in `{ref}` @ `{sha_short}`.",
        "",
        "| Severity | Count |",
        "|----------|-------|",
        f"| Critical | {crit} |",
        f"| High | {high} |",
        f"| Medium | {med} |",
        f"| Low | {low} |",
        "",
        f"**Overall score:** {overall}/100 (grade {grade})",
        "",
    ]

    findings: list[dict[str, Any]] = list(scan.get("findings") or [])
    findings.sort(
        key=lambda f: (
            _SEVERITY_ORDER.index(str(f.get("severity", "medium")).lower())
            if str(f.get("severity", "medium")).lower() in _SEVERITY_ORDER
            else 99,
            str((f.get("location") or {}).get("file", "")),
            int((f.get("location") or {}).get("line", 0)),
        )
    )

    if findings:
        lines.extend(["## Findings", ""])
        for idx, finding in enumerate(findings[:50], start=1):
            sev = str(finding.get("severity", "medium")).title()
            rule = finding.get("rule", "unknown")
            loc = finding.get("location") or {}
            file_line = f"{loc.get('file', '?')}:{loc.get('line', '?')}"
            message = finding.get("message", "")
            recommendation = finding.get("recommendation", "")
            lines.append(f"### {idx}. {sev} — `{rule}`")
            lines.append("")
            lines.append(f"- **File:** `{file_line}`")
            lines.append(f"- **Message:** {message}")
            if recommendation:
                lines.append(f"- **Recommendation:** {recommendation}")
            lines.append("")
        if len(findings) > 50:
            lines.append(f"_…and {len(findings) - 50} more finding(s) not listed._")
            lines.append("")

    lines.extend(
        [
            "## Next steps",
            "",
            "1. Fix findings on a branch; re-run workflow via **Actions → SecMCP Daily Scan → Run workflow**.",
            f"2. Add SecMCP MCP to your IDE for in-loop scans — see [secmcp README]({docs_url}).",
            "3. Audit `.cursor/mcp.json` with the MCP security checklist in `prompts-directory-main/skills/`.",
            "",
            "---",
            "",
            "*Generated by SecMCP GitHub Action. This issue does not contain full API keys or secrets.*",
        ]
    )

    return title, "\n".join(lines)


def _sarif_rule_id(rule_name: str) -> str:
    normalized = re.sub(r"[^a-z0-9]+", "-", rule_name.lower()).strip("-")
    return f"secmcp.{normalized or 'finding'}"


def build_sarif_from_scan(scan: dict[str, Any]) -> dict[str, Any]:
    """Convert `scan_repository_sync` JSON to SARIF 2.1.0 for GitHub Code Scanning."""
    rules: dict[str, dict[str, Any]] = {}
    sarif_results: list[dict[str, Any]] = []

    for finding in scan.get("findings") or []:
        rule_name = str(finding.get("rule", "unknown"))
        rule_id = _sarif_rule_id(rule_name)
        severity = str(finding.get("severity", "medium")).lower()
        rules[rule_id] = {
            "id": rule_id,
            "name": rule_name,
            "shortDescription": {"text": rule_name},
            "fullDescription": {
                "text": str(finding.get("message", "SecMCP finding")),
            },
            "properties": {"severity": severity, "category": finding.get("category")},
        }
        loc = finding.get("location") or {}
        file_uri = str(loc.get("file", "unknown")).replace("\\", "/")
        line = int(loc.get("line", 1))
        column = int(loc.get("column", 1))
        sarif_results.append(
            {
                "ruleId": rule_id,
                "level": SARIF_LEVELS.get(severity, "warning"),
                "message": {"text": str(finding.get("message", rule_name))},
                "locations": [
                    {
                        "physicalLocation": {
                            "artifactLocation": {"uri": file_uri},
                            "region": {
                                "startLine": line,
                                "startColumn": max(column, 1),
                            },
                        }
                    }
                ],
                "properties": {
                    "recommendation": finding.get("recommendation"),
                    "category": finding.get("category"),
                },
            }
        )

    return {
        "version": SARIF_VERSION,
        "$schema": SARIF_SCHEMA,
        "runs": [
            {
                "tool": {
                    "driver": {
                        "name": "secmcp",
                        "informationUri": "https://github.com",
                        "semanticVersion": "0.1.0",
                        "rules": list(rules.values()),
                    }
                },
                "results": sarif_results,
            }
        ],
    }


def write_sarif_file(scan: dict[str, Any], output_path: Path) -> None:
    output_path = output_path.expanduser()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        json.dumps(build_sarif_from_scan(scan), indent=2),
        encoding="utf-8",
    )


def _sorted_findings(scan: dict[str, Any]) -> list[dict[str, Any]]:
    findings: list[dict[str, Any]] = list(scan.get("findings") or [])
    findings.sort(
        key=lambda f: (
            _SEVERITY_ORDER.index(str(f.get("severity", "medium")).lower())
            if str(f.get("severity", "medium")).lower() in _SEVERITY_ORDER
            else 99,
            str((f.get("location") or {}).get("file", "")),
            int((f.get("location") or {}).get("line", 0)),
        )
    )
    return findings


def format_vulnerabilities_txt(scan: dict[str, Any]) -> str:
    """Plain-text report of every finding (for vulnerabilities.txt / CI artifacts)."""
    counts = scan.get("severity_counts") or {}
    total = int(scan.get("count", len(scan.get("findings") or [])))
    root = scan.get("root") or scan.get("source") or "—"
    overall = scan.get("overall_score", "—")
    grade = scan.get("grade", "—")

    lines = [
        "SecMCP vulnerability report",
        "=" * 40,
        f"Root / source: {root}",
        f"Overall score: {overall}/100 (grade {grade})",
        f"Total findings: {total}",
        "",
        "Severity counts:",
    ]
    for sev in _SEVERITY_ORDER:
        n = int(counts.get(sev, 0))
        if n:
            lines.append(f"  {sev}: {n}")
    lines.append("")
    lines.append("Findings")
    lines.append("-" * 40)

    findings = _sorted_findings(scan)
    if not findings:
        lines.append("(none)")
    else:
        for idx, finding in enumerate(findings, start=1):
            sev = str(finding.get("severity", "medium")).upper()
            rule = finding.get("rule", "unknown")
            loc = finding.get("location") or {}
            file_line = f"{loc.get('file', '?')}:{loc.get('line', '?')}"
            lines.append(f"\n{idx}. [{sev}] {rule} @ {file_line}")
            message = finding.get("message", "")
            if message:
                lines.append(f"   Message: {message}")
            recommendation = finding.get("recommendation", "")
            if recommendation:
                lines.append(f"   Fix: {recommendation}")
            category = finding.get("category")
            if category:
                lines.append(f"   Category: {category}")
            stage = finding.get("vibe_stage")
            if stage is not None:
                title = finding.get("vibe_stage_title", "")
                lines.append(f"   Vibe stage: {stage} — {title}")

    warnings = list(scan.get("rules_load_warnings") or [])
    if warnings:
        lines.extend(["", "Rule load warnings", "-" * 40])
        for w in warnings:
            lines.append(f"- {w}")

    lines.append("")
    lines.append("Generated by SecMCP. No full API keys or secrets are included.")
    return "\n".join(lines)


def default_vulnerabilities_path(scan: dict[str, Any]) -> Path:
    """Default vulnerabilities.txt beside repo root when scanning a directory."""
    root = scan.get("root")
    if root:
        return Path(str(root)).resolve() / "vulnerabilities.txt"
    return Path.cwd() / "vulnerabilities.txt"


def write_vulnerabilities_txt_file(
    scan: dict[str, Any],
    output_path: Path | None = None,
) -> Path:
    path = (output_path or default_vulnerabilities_path(scan)).expanduser().resolve()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(format_vulnerabilities_txt(scan), encoding="utf-8")
    return path


def _mermaid_escape(label: str, max_len: int = 48) -> str:
    text = re.sub(r"[\[\]\"#\n\r]", " ", label).strip()
    if len(text) > max_len:
        text = text[: max_len - 1] + "…"
    return text or "finding"


def build_interactive_graph_mermaid(scan: dict[str, Any], *, max_nodes: int = 24) -> str:
    """Mermaid flowchart for Cursor / GitHub interactive graph rendering."""
    overall = scan.get("overall_score", "—")
    grade = scan.get("grade", "—")
    total = int(scan.get("count", len(scan.get("findings") or [])))
    root = _mermaid_escape(str(scan.get("root") or scan.get("source") or "scan target"), 36)

    lines = [
        "flowchart TB",
        f'  scan["SecMCP scan<br/>{root}<br/>{total} finding(s)<br/>score {overall} ({grade})"]',
    ]

    counts = scan.get("severity_counts") or {}
    sev_nodes: list[str] = []
    for sev in _SEVERITY_ORDER:
        n = int(counts.get(sev, 0))
        if not n:
            continue
        node_id = f"sev_{sev}"
        sev_nodes.append(node_id)
        lines.append(f'  {node_id}["{sev.title()}<br/>{n}"]')
        lines.append(f"  scan --> {node_id}")

    findings = _sorted_findings(scan)
    shown = findings[:max_nodes]
    for i, finding in enumerate(shown):
        sev = str(finding.get("severity", "medium")).lower()
        parent = f"sev_{sev}" if int(counts.get(sev, 0)) else "scan"
        rule = _mermaid_escape(str(finding.get("rule", "unknown")))
        loc = finding.get("location") or {}
        loc_s = _mermaid_escape(f"{loc.get('file', '?')}:{loc.get('line', '?')}", 40)
        fid = f"f{i}"
        lines.append(f'  {fid}["{rule}<br/>{loc_s}"]')
        lines.append(f"  {parent} --> {fid}")

    remaining = len(findings) - len(shown)
    if remaining > 0:
        lines.append(f'  more["… {remaining} more in vulnerabilities.txt"]')
        lines.append("  scan --> more")

    triggered = scan.get("vibe_stages_triggered") or []
    if triggered:
        lines.append('  vibe["Vibe stages lit"]')
        lines.append("  scan --> vibe")
        for j, block in enumerate(triggered[:5]):
            sid = f"vs{j}"
            title = _mermaid_escape(
                f"Stage {block.get('stage')} — {block.get('title', '')}", 44
            )
            lines.append(f'  {sid}["{title}"]')
            lines.append(f"  vibe --> {sid}")

    return "\n".join(lines)


def attach_interactive_graph(scan: dict[str, Any]) -> dict[str, Any]:
    """Add `interactive_graph` (Mermaid) and a graph section to `detailed_report` when present."""
    merged = dict(scan)
    mermaid = build_interactive_graph_mermaid(merged)
    merged["interactive_graph"] = mermaid
    report = str(merged.get("detailed_report") or "")
    graph_block = f"### Interactive graph\n\n```mermaid\n{mermaid}\n```"
    if "interactive_graph" not in report.lower() and "```mermaid" not in report:
        merged["detailed_report"] = (report.rstrip() + "\n\n" + graph_block).strip()
    return merged
