"""GitHub issue formatting for Phase 2 daily scan."""

from secmcp.reporting import (
    build_interactive_graph_mermaid,
    build_sarif_from_scan,
    format_github_issue,
    format_vulnerabilities_txt,
    write_sarif_file,
    write_vulnerabilities_txt_file,
)


def _sample_scan(**overrides: object) -> dict:
    base = {
        "count": 2,
        "severity_counts": {"critical": 1, "high": 1},
        "overall_score": 62.0,
        "grade": "D",
        "findings": [
            {
                "severity": "critical",
                "rule": "openai_api_key",
                "message": "Hardcoded key",
                "recommendation": "Rotate and use env.",
                "location": {"file": "src/a.py", "line": 1},
            },
            {
                "severity": "high",
                "rule": "eval_usage",
                "message": "eval()",
                "recommendation": "Remove eval.",
                "location": {"file": "src/b.js", "line": 4},
            },
        ],
    }
    base.update(overrides)
    return base


def test_format_github_issue_title_and_body() -> None:
    scan = _sample_scan()
    scan = {
        "count": 2,
        "severity_counts": {"critical": 1, "high": 1},
        "overall_score": 62.0,
        "grade": "D",
        "findings": [
            {
                "severity": "critical",
                "rule": "openai_api_key",
                "message": "Hardcoded key",
                "recommendation": "Rotate and use env.",
                "location": {"file": "src/a.py", "line": 1},
            },
            {
                "severity": "high",
                "rule": "eval_usage",
                "message": "eval()",
                "recommendation": "Remove eval.",
                "location": {"file": "src/b.js", "line": 4},
            },
        ],
    }
    title, body = format_github_issue(scan, ref="main", sha="abc1234567890")
    assert "[SecMCP] Daily scan — 2 findings" in title
    assert "1 critical" in title
    assert "62.0/100" in body
    assert "`openai_api_key`" in body
    assert "abc1234" in body
    assert "Generated by SecMCP GitHub Action" in body


def test_format_github_issue_singular_finding_and_clean_scan() -> None:
    scan = {
        "count": 1,
        "severity_counts": {"medium": 1},
        "overall_score": 90.0,
        "grade": "A",
        "findings": [
            {
                "severity": "medium",
                "rule": "todo_fixme",
                "message": "FIXME left in code",
                "location": {"file": "x.py", "line": 2},
            },
        ],
    }
    title, body = format_github_issue(scan, ref="develop", sha="")
    assert title == "[SecMCP] Daily scan — 1 finding"
    assert "critical" not in title
    assert "develop" in body
    assert "@ `unknown`" in body


def test_format_github_issue_sorts_findings_critical_first() -> None:
    scan = _sample_scan(
        findings=[
            {
                "severity": "low",
                "rule": "low_rule",
                "message": "low",
                "location": {"file": "z.py", "line": 9},
            },
            {
                "severity": "critical",
                "rule": "crit_rule",
                "message": "crit",
                "location": {"file": "a.py", "line": 1},
            },
        ],
        count=2,
        severity_counts={"critical": 1, "low": 1},
    )
    _, body = format_github_issue(scan)
    crit_pos = body.index("`crit_rule`")
    low_pos = body.index("`low_rule`")
    assert crit_pos < low_pos


def test_format_github_issue_truncates_long_finding_lists() -> None:
    findings = [
        {
            "severity": "low",
            "rule": f"rule_{i}",
            "message": "m",
            "location": {"file": f"f{i}.py", "line": i},
        }
        for i in range(55)
    ]
    scan = {
        "count": 55,
        "severity_counts": {"low": 55},
        "overall_score": 10.0,
        "grade": "F",
        "findings": findings,
    }
    _, body = format_github_issue(scan)
    listed_rules = body.count(" — `rule_")
    assert listed_rules == 50
    assert "`rule_54`" not in body
    assert "5 more finding(s) not listed" in body


def test_format_github_issue_includes_docs_url() -> None:
    _, body = format_github_issue(
        _sample_scan(),
        docs_url="https://github.com/org/repo/blob/main/secmcp/README.md",
    )
    assert "[secmcp README](https://github.com/org/repo/blob/main/secmcp/README.md)" in body


def test_build_sarif_from_scan_maps_rules_and_levels() -> None:
    sarif = build_sarif_from_scan(_sample_scan())
    assert sarif["version"] == "2.1.0"
    run = sarif["runs"][0]
    assert run["tool"]["driver"]["name"] == "secmcp"
    assert len(run["results"]) == 2
    levels = {r["level"] for r in run["results"]}
    assert "error" in levels
    rule_ids = {r["ruleId"] for r in run["results"]}
    assert "secmcp.openai-api-key" in rule_ids


def test_write_sarif_file_roundtrip(tmp_path) -> None:
    out = tmp_path / "report.sarif"
    write_sarif_file(_sample_scan(), out)
    text = out.read_text(encoding="utf-8")
    assert '"secmcp"' in text
    assert "physicalLocation" in text


def test_format_vulnerabilities_txt_lists_all_findings() -> None:
    text = format_vulnerabilities_txt(_sample_scan())
    assert "SecMCP vulnerability report" in text
    assert "[CRITICAL] openai_api_key" in text
    assert "[HIGH] eval_usage" in text
    assert "Rotate and use env." in text


def test_write_vulnerabilities_txt_file(tmp_path) -> None:
    out = tmp_path / "vulnerabilities.txt"
    write_vulnerabilities_txt_file(_sample_scan(), out)
    body = out.read_text(encoding="utf-8")
    assert "eval_usage" in body
    assert out.name == "vulnerabilities.txt"


def test_build_interactive_graph_mermaid_structure() -> None:
    mermaid = build_interactive_graph_mermaid(_sample_scan())
    assert mermaid.startswith("flowchart TB")
    assert "sev_critical" in mermaid
    assert "openai_api_key" in mermaid
